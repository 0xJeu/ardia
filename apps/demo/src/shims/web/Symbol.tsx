const FILLED = new Set<LucideIcon>([Circle, Star, Heart, Pin, Bookmark, Play, Pause, User]);

const STROKES = { light: 1.5, regular: 1.75, medium: 2, semibold: 2.25, bold: 2.5 } as const;

function iconFor(name: string): { Icon: LucideIcon; filled: boolean } | null {
  const filled = name.endsWith(".fill");
  const base = filled ? name.slice(0, -".fill".length) : name;
  const Icon = ICONS[name] ?? ICONS[base];
  return Icon ? { Icon, filled } : null;
}

export type SymbolProps = ViewProps & {
  name: string;
  size?: number;
  weight?: keyof typeof STROKES;
  color?: string;
};

export function Symbol({ name, size = 13, weight = "regular", color = "currentColor", style, ...props }: SymbolProps) {
  const found = iconFor(name);
  if (!found) noteMissing(`symbol ${name}`);
  const box = Math.round(size * 1.15);
  return (
    <View pointerEvents="none" {...props} style={[{ alignItems: "center", justifyContent: "center" }, style]}>
      {found ? (
        <found.Icon
          size={box}
          color={color}
          strokeWidth={STROKES[weight]}
          fill={found.filled && FILLED.has(found.Icon) ? color : "none"}
          aria-hidden
        />
      ) : (
        <span style={{ width: box * 0.7, height: box * 0.7, borderRadius: box * 0.2, border: `1.5px solid ${color}`, opacity: 0.5, boxSizing: "border-box" }} />
      )}
    </View>
  );
}
